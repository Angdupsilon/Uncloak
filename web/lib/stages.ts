/**
 * Project Time Machine stages.
 *
 * Five illustrative stages of a data-center build. Each maps to evidence the
 * project already stores, so dragging the as-of slider moves a site up the
 * ladder exactly when the records say it did.
 *
 * The clips are ONE generic set reused for all projects - they are an
 * illustration of a stage, never a picture of a specific site. Every surface
 * that renders one must say so (see StageClip).
 */

export type StageId = "filed" | "certified" | "construction" | "complete" | "energized";

export interface Stage {
  id: StageId;
  /** Ascending; higher means further along. */
  rank: number;
  label: string;
  /** What in the record puts a project here, shown under the clip. */
  basis: string;
  /** Video served from public/illustrations, generated by etl/generate_imagery.py. */
  clip: string;
  /** Still of the same stage, shown while the clip loads. */
  poster: string;
}

