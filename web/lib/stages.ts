export const STAGE_BY_ID = Object.fromEntries(STAGES.map((s) => [s.id, s])) as Record<StageId, Stage>;

/** Highest stage the evidence supports at the selected as-of date. */
export function stageFor(input: {
  factors?: Record<string, boolean> | null;
  currentStatus?: string | null;
  hasAnyEvidence?: boolean;
}): Stage | null {
  const f = input.factors ?? {};
  const status = input.currentStatus ?? null;

  // Scored factors are computed per week, so they already respect as-of. Status
  // is a lighter-touch signal used only to lift a project that has a TDLR
  // milestone the checklist does not cover.
  if (f.inspection_done || status === "inspection_complete") return STAGE_BY_ID.complete;
  if (f.tdlr_registered || status === "registered") return STAGE_BY_ID.construction;
  if (f.comptroller_certified || f.tceq_permit || status === "design_review_complete") return STAGE_BY_ID.certified;
  if (input.hasAnyEvidence || Object.values(f).some(Boolean)) return STAGE_BY_ID.filed;
  return null;
}

/**
 * Same ladder as stageFor, expressed over the fields a Site row carries.
 * Org listings do not load per-site scoring factors, so this reads the
 * equivalent columns instead - deliberately the same rungs in the same order,
 * so a site shows the same stage wherever it is listed.
 */
export function stageForSite(site: {
  inspected?: boolean;
  tdlr_registrations?: number;
  certified_at?: string | null;
  has_permit?: boolean;
  first_evidence?: string | null;
}): Stage | null {
  if (site.inspected) return STAGE_BY_ID.complete;
  if ((site.tdlr_registrations ?? 0) > 0) return STAGE_BY_ID.construction;
  if (site.certified_at || site.has_permit) return STAGE_BY_ID.certified;
  if (site.first_evidence) return STAGE_BY_ID.filed;
  return null;
}
